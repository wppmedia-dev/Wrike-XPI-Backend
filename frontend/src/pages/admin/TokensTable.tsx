/* The API Tokens table: one row per token record the token service has
 * issued, with the module permissions that govern it reachable from the row
 * itself (the modal is owned by AdminDashboard, exactly as the portal-user
 * permissions modal is).
 *
 * The row deliberately shows the token's *identity* (which environment and
 * account it acts for, which Wrike user generated it, and what it is allowed
 * to do) and never the credential it carries. An admin who needs the token
 * value uses the console's token tooling; this screen can't leak it because
 * the API never sends it. */

/* ── Advanced filters ─────────────────────────────────────────────────
   The table's own search box is one substring over the whole row; this is
   the per-column version of it, one control per column that can meaningfully
   be narrowed (every column except Actions, which is a menu).

   The definitions below are the single authority: they render the controls
   and they decide what each control matches, so a filter can never be
   displayed without being applied or applied without being displayed. */

type FilterKey =
  | "env"
  | "tokenId"
  | "client"
  | "account"
  | "creator"
  | "access"
  | "validity"
  | "updated"
  | "status";

interface FilterDef {
  key: FilterKey;
  label: string;
  kind: "text" | "select" | "environment";
  placeholder?: string;
  options?: { value: string; label: string }[];
}

/** Option value standing for "tokens that are not attached to an environment". */
const NO_ENVIRONMENT = "\u0000none";

/** Days before expiry at which a token is worth flagging: enough notice to
    re-authenticate before whatever is using it starts failing. */
const EXPIRY_WARNING_DAYS = 14;

const MS_PER_DAY = 24 * 60 * 60 * 1000;

