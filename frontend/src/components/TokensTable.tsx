/* The Tokens table: one row per token record the token service has
 * issued, with the module permissions that govern it reachable from the row
 * itself (the modal is owned by AdminDashboard, exactly as the portal-user
 * permissions modal is).
 *
 * The row deliberately shows the token's *identity* (which environment and
 * account it acts for, which Wrike user generated it, and what it is allowed
 * to do) and never the credential it carries. An admin who needs the token
 * value uses the console's token tooling; this screen can't leak it because
 * the API never sends it. */

/* ── Advanced filters ─────────────────────────────────────────────────
   The table's own search box is one substring over the whole row; this is
   the per-column version of it, one control per column that can meaningfully
   be narrowed (every column except Actions, which is a menu).

   The definitions below are the single authority for the *controls*: they
   render the inputs and they name the query parameter each one sends. What
   each control matches is decided by the server
   (src/utils/tokenFilters.js), because it is the server that now applies the
   filter — a filter applied in the browser only ever narrows the rows the
   browser happens to hold.

   The panel edits a DRAFT. Nothing is fetched until Done, so a half-typed
   account id does not become a query, and the count in the footer always
   describes what is on screen rather than what is in the boxes. */

type FilterKey =
  | "env"
  | "tokenId"
  | "client"
  | "account"
  | "creator"
  | "access"
  | "validity"
  | "updated"
  | "status";

/** The nine controls, keyed the way the table and the pages talk about them. */
export type TokenFilters = Record<FilterKey, string>;

interface FilterDef {
  key: FilterKey;
  /** The query parameter this control fills, and so the field the server
      reads. One name per filter, in one place. */
  param: keyof TokenListQuery;
  label: string;
  kind: "text" | "select" | "environment";
  placeholder?: string;
  options?: { value: string; label: string }[];
}

